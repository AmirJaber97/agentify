export function toCard(a: Agent, outstanding: number, focus: string, warning: string | null): AgentCard {
  return {
    id: a.id,
    name: a.name,
    icon: a.icon ?? '⬡',
    short_purpose: (a.description ?? '').split(';')[0] ?? '',
    category: a.category ?? 'general',
    enabled: a.enabled ?? true,
    status: a.status ?? 'IDLE',
    privacy_class: a.privacy_class ?? 'PERSONAL',
    model_policy: a.model_policy ?? 'BALANCED',
    last_activity_at: a.last_activity_at ?? null,
    current_focus: focus,
    outstanding_tasks: outstanding,
    warning,
    metrics: {},
    ui_metadata: a.ui_metadata ?? {},
  };
}

